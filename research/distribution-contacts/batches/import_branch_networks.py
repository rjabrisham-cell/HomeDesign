DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")


def to_mobile(v: str) -> str | None:
    d = re.sub(r"\D", "", str(v).translate(DIGITS))
    if d.startswith("98") and len(d) >= 12:
        d = "0" + d[2:]
    if len(d) == 10 and d.startswith("9"):
        d = "0" + d
    if len(d) == 11 and d.startswith("09"):
        return d
    return None


def land(v: str) -> str | None:
    d = re.sub(r"\D", "", str(v).translate(DIGITS).split("-")[0] if "-" in str(v)[:4] else str(v).translate(DIGITS))
    # take first phone-like chunk
    for part in re.split(r"[\s,/|]+", str(v).translate(DIGITS)):
        dd = re.sub(r"\D", "", part)
        if not dd or dd.startswith("09") or (len(dd) == 10 and dd.startswith("9")):
            continue
        if dd.startswith("98"):
            dd = "0" + dd[2:]
        if not dd.startswith("0") and len(dd) in (7, 8, 10):
            if len(dd) == 10:
                dd = "0" + dd
            else:
                continue
        if dd.startswith("0") and len(dd) >= 10:
            return dd
    return None


